//! End-to-end ECDSA verify benchmark — same RFC6979 vector as bench.c.
use p256_verify::verify;
use std::hint::black_box;

fn rdtsc() -> u64 { unsafe { core::arch::x86_64::_rdtsc() } }

// RFC 6979 'sample' vector (same as asm bench.c)
const PUB: [u8; 65] = [
    0x04,
    0x60,0xfe,0xd4,0xba,0x25,0x5a,0x9d,0x31,0xc9,0x61,0xeb,0x74,0xc6,0x35,0x6d,0x68,
    0xc0,0x49,0xb8,0x92,0x3b,0x61,0xfa,0x6c,0xe6,0x69,0x62,0x2e,0x60,0xf2,0x9f,0xb6,
    0x79,0x03,0xfe,0x10,0x08,0xb8,0xbc,0x99,0xa4,0x1a,0xe9,0xe9,0x56,0x28,0xbc,0x64,
    0xf2,0xf1,0xb2,0x0c,0x2d,0x7e,0x9f,0x51,0x77,0xa3,0xc2,0x94,0xd4,0x46,0x22,0x99,
];
const HASH: [u8; 32] = [
    0xaf,0x2b,0xdb,0xe1,0xaa,0x9b,0x6e,0xc1,0xe2,0xad,0xe1,0xd6,0x94,0xf4,0x1f,0xc7,
    0x1a,0x83,0x1d,0x02,0x68,0xe9,0x89,0x15,0x62,0x11,0x3d,0x8a,0x62,0xad,0xd1,0xbf,
];
const SIG: [u8; 64] = [
    0xef,0xd4,0x8b,0x2a,0xac,0xb6,0xa8,0xfd,0x11,0x40,0xdd,0x9c,0xd4,0x5e,0x81,0xd6,
    0x9d,0x2c,0x87,0x7b,0x56,0xaa,0xf9,0x91,0xc3,0x4d,0x0e,0xa8,0x4e,0xaf,0x37,0x16,
    0xf7,0xcb,0x1c,0x94,0x2d,0x65,0x7c,0x41,0xd4,0x36,0xc7,0xa1,0xb6,0xe2,0x9f,0x65,
    0xf3,0xe9,0x00,0xdb,0xb9,0xaf,0xf4,0x06,0x4d,0xc4,0xab,0x2f,0x84,0x3a,0xcd,0xa8,
];

fn main() {
    // Correctness first
    assert!(verify(&SIG, &PUB, &HASH), "RFC6979 vector failed");
    // Tamper — should fail
    let mut bad = SIG; bad[0] ^= 1;
    assert!(!verify(&bad, &PUB, &HASH), "tampered sig passed");
    println!("correctness: OK");

    // Warmup
    for _ in 0..10 { black_box(verify(&SIG, &PUB, &HASH)); }

    const N: u64 = 200;
    let start = rdtsc();
    for _ in 0..N {
        black_box(verify(black_box(&SIG), black_box(&PUB), black_box(&HASH)));
    }
    let elapsed = rdtsc() - start;
    println!("verify: {} cyc/call", elapsed / N);
}
