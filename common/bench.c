static const unsigned char SIG[64] = {
    0xef,0xd4,0x8b,0x2a,0xac,0xb6,0xa8,0xfd,0x11,0x40,0xdd,0x9c,0xd4,0x5e,0x81,0xd6,
    0x9d,0x2c,0x87,0x7b,0x56,0xaa,0xf9,0x91,0xc3,0x4d,0x0e,0xa8,0x4e,0xaf,0x37,0x16,
    0xf7,0xcb,0x1c,0x94,0x2d,0x65,0x7c,0x41,0xd4,0x36,0xc7,0xa1,0xb6,0xe2,0x9f,0x65,
    0xf3,0xe9,0x00,0xdb,0xb9,0xaf,0xf4,0x06,0x4d,0xc4,0xab,0x2f,0x84,0x3a,0xcd,0xa8
};

int main(void) {
    /* Warmup + correctness. */
    int r = tv_ecdsa_p256_verify_asm(SIG, 64, PUB, 65, HASH, 32);
    if (r != 1) { printf("FAIL: verify returned %d (expected 1)\n", r); return 1; }

    /* Measure: median of several runs. */
    uint64_t best = (uint64_t)-1;
    for (int i = 0; i < 50; i++) {
        uint64_t t0 = rdtsc();
        tv_ecdsa_p256_verify_asm(SIG, 64, PUB, 65, HASH, 32);
        uint64_t t1 = rdtsc();
        uint64_t d = t1 - t0;
        if (d < best) best = d;
    }
    printf("cycles: %llu\n", (unsigned long long)best);
    return 0;
}
